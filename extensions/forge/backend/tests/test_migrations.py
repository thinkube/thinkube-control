"""The models and the migrations describe the same schema.

The backend applies the migrations when it starts and nothing else, so a
model change without its migration is stopped here, before the build."""

from pathlib import Path

from alembic import command
from alembic.config import Config

BACKEND = Path(__file__).resolve().parents[1]


def test_the_models_match_the_migrations(db_engine):
    with db_engine.begin() as connection:
        migrations = Config(str(BACKEND / "alembic.ini"))
        migrations.set_main_option("script_location", str(BACKEND / "alembic"))
        migrations.attributes["connection"] = connection
        # Raises AutoGenerateDiffsDetected, naming each difference
        command.check(migrations)
